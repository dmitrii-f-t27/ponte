    assert((au_tap_action(true, 3, false, false, false) == AU_TAP_UPDATE));
    assert((au_tap_action(true, 0, false, false, false) == AU_TAP_WAIT));
    assert((au_tap_action(true, 1, false, true, false) == AU_TAP_UPDATE));
