    assert((au_pacing_sleep_nanos(0, 0, 0, 48000.0) == 0));
    assert((au_conversion_path(true, true) == AU_CONVERT_NONE));
    assert((au_conversion_path(false, true) == AU_CONVERT_DOWNMIX));
    assert((au_conversion_path(false, false) == AU_CONVERT_RESAMPLE));
    assert((au_is_usable_tap_format(true, true, 32, 48000.0) == true));
    assert((au_is_usable_tap_format(true, false, 16, 48000.0) == false));
