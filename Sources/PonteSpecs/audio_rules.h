    assert((au_tap_action(true, 0, false, false, true) == AU_TAP_WAIT));
    uint32_t bits = 0;
    uint32_t bad = 0;
    while ((bits < 32)) {
        bool attached = ((bits & 1) == 1);
        bool same = ((bits & 2) == 2);
        bool global = ((bits & 4) == 4);
        bool force = ((bits & 8) == 8);
        int64_t desired = 0;
        if (((bits & 16) == 16)) {
            desired = 3;
        }
        int64_t a = au_tap_action(attached, desired, same, global, force);
        if (((a < AU_TAP_KEEP) || (a > AU_TAP_REBUILD))) {
            bad = (bad + 1);
        }
        if ((force && ((a == AU_TAP_KEEP) || (a == AU_TAP_UPDATE)))) {
            bad = (bad + 1);
        }
        if ((global && (a == AU_TAP_WAIT))) {
            bad = (bad + 1);
        }
        bits = (bits + 1);
    }
    assert((bad == 0));
    assert((au_mic_start_decision(3) == AU_MIC_START));
    assert((au_mic_start_decision(0) == AU_MIC_REQUEST_FIRST));
    assert((au_mic_start_decision(1) == AU_MIC_DENIED));
    assert((au_mic_start_decision(2) == AU_MIC_DENIED));
    assert((au_mic_start_decision(99) == AU_MIC_DENIED));
