    assert((au_frames_per_chunk(22050.0, AU_CHUNK_SECONDS) == 2205));
    assert((au_frames_per_chunk(11025.0, AU_CHUNK_SECONDS) == 1103));
    assert((au_frames_per_chunk(16000.0, 0.02) == 320));
    assert((au_frames_per_chunk(0.0, AU_CHUNK_SECONDS) == 1));
    assert((au_chunk_count(10, 4) == 3));
    assert((au_chunk_length(10, 4, 0) == 4));
    assert((au_chunk_length(10, 4, 1) == 4));
    assert((au_chunk_length(10, 4, 2) == 2));
    assert((au_chunk_length(10, 4, 3) == 0));
    assert((au_chunk_count(8, 4) == 2));
    assert((au_chunk_length(8, 4, 1) == 4));
    assert((au_chunk_count(0, 4) == 0));
    assert((au_chunk_count(3, 0) == 0));
    assert((au_chunk_length(3, 0, 0) == 0));
    assert((au_conversion_capacity(22050, 22050.0, 48000.0) == (48000 + 1024)));
    assert((au_conversion_capacity(1, 44100.0, 48000.0) == (2 + 1024)));
    assert((au_conversion_capacity(10, 0.0, 48000.0) == (10 + 1024)));
    assert((au_needs_resample(48000.0, 44100.0) == true));
    assert((au_needs_resample(48000.0, 48000.0) == false));
    assert((au_converter_should_downmix(2, 1) == true));
    assert((au_converter_should_downmix(1, 2) == false));
    assert((au_session_rate(0.0, 44100.0) == 44100.0));
    assert((au_session_rate(48000.0, 44100.0) == 48000.0));
    int64_t total = 0;
    uint32_t bad = 0;
    while ((total < 50)) {
        int64_t chunk = 1;
        while ((chunk < 12)) {
            int64_t sum = 0;
            int64_t idx = 0;
            while ((idx < au_chunk_count(total, chunk))) {
                int64_t len = au_chunk_length(total, chunk, idx);
                if (((len <= 0) || (len > chunk))) {
                    bad = (bad + 1);
                }
                sum = (sum + len);
                idx = (idx + 1);
            }
            if ((sum != total)) {
                bad = (bad + 1);
            }
            chunk = (chunk + 1);
        }
        total = (total + 1);
    }
    assert((bad == 0));
    assert((au_pacing_sleep_nanos(1000, 1000, 4800, 48000.0) == 100000000));
    assert((au_pacing_sleep_nanos(0, 40000000, 4800, 48000.0) == 60000000));
