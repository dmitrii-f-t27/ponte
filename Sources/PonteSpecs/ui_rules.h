bool ui_button_enabled(int32_t button, int32_t run_state, int32_t incoming_lines, int32_t outgoing_lines, bool has_blackhole, bool busy) {
    bool running = (run_state == UI_RUN_RUNNING);
    if ((button == UI_BTN_START_STOP)) {
        return ((run_state == UI_RUN_IDLE) || running);
    }
    if ((button == UI_BTN_SOURCE)) {
        return (run_state == UI_RUN_IDLE);
    }
    if ((button == UI_BTN_REPLAY_INCOMING)) {
        return (running && (incoming_lines > 0));
    }
    if ((button == UI_BTN_REPLAY_OUTGOING)) {
        return (running && (outgoing_lines > 0));
    }
    if ((button == UI_BTN_SAVE_TRANSCRIPT)) {
        return ((incoming_lines + outgoing_lines) > 0);
    }
    if ((((button == UI_BTN_PAUSE_VOICE) || (button == UI_BTN_MODE)) || (button == UI_BTN_VOICE_TOGGLE))) {
        return true;
    }
    if ((button == UI_BTN_TALK_PAD)) {
        return running;
    }
    if ((button == UI_BTN_TEST_CALL)) {
        return (has_blackhole && (busy == false));
    }
    if ((button == UI_BTN_TEST_HEADPHONES)) {
        return (busy == false);
    }
    return false;
}

