bool ui_equals_row(uint8_t text[static 64], int64_t len, int64_t row) {
    int64_t n = UI_ROW_LENGTHS[row];
    if ((len != n)) {
        return false;
    }
    int64_t off = UI_ROW_OFFSETS[row];
    int64_t i = 0;
    while ((i < n)) {
        if ((text[i] != UI_ROW_TEXT[(off + i)])) {
            return false;
        }
        i = (i + 1);
    }
    return true;
}

